// =====================================================================
// 跳舞演示轨迹 —— 「模拟仿真」与「真实监控(离线演示)」共用同一段动作。
//
// 关节空间轨迹（周期 8s），经 manager 的姿态平滑后丝滑循环：
//   J1 左右摆头 / J2 抬臂起伏 / J3 肘部舒展 / J4 翻腕 / J5 点头 / J6 腕部摆动
//
// ★ 平滑性（"保证不卡顿丝滑"）：
//   所有通道都用正弦，且在循环边界(t=0 与 t=8s)取相同相位 → 首尾连续，
//   循环播放不跳变；J6 用 sin 摆动而不是 `((t*90)%360)-180` 那种 360° 锯齿
//   回绕（锯齿会让腕部每 4s 向后急转一整圈，肉眼就是"卡一下"）。
//
// ★ 离地间隙（"不能穿地、也不该全场无提示"）：
//   官方数模（ER8-700H 真实几何）对 J2 的响应与程序化模型**方向相反** ——
//   J2 偏正会把手臂往下折，容易扫到地面。本轨迹的 J2 偏置取负值（手臂抬起），
//   J3 做 ±45° 的肘部反相摆动。用 tools/measure_clearance.mjs 实测：
//     一周期内 J1 子树最低点 ≈ 120 mm
//     → 高于"危险 80mm"，不穿地、不报红；
//     → 低于"接近 150mm"，所以演示时地面报警垫会变黄，能直观看到"提前提醒"。
//   改轨迹后务必重跑 measure_clearance.mjs 校核，最低点必须 > 0（更不能 < 0）。
// =====================================================================

export const DANCE_PERIOD = 8;   // 秒 / 一个循环

/**
 * 计算 tSec 时刻的关节角(度)。
 * @param {number} tSec 演示已运行秒数
 * @returns {number[]} [J1..J6] 角度
 */
export function dancePose(tSec) {
  const p = (tSec % DANCE_PERIOD) / DANCE_PERIOD;
  const w = 2 * Math.PI * p;
  return [
    Math.sin(w) * 60,                       // J1 左右摆头（±60°）
    -20 + Math.sin(w * 2) * 20,             // J2 抬臂起伏（-40° ~ 0°，手臂始终抬起）
    Math.sin(w * 2 + Math.PI) * 45,         // J3 肘部舒展（±45°，与 J2 反相）
    Math.sin(w * 1.5) * 120,                // J4 腕部翻滚（±120°）
    Math.sin(w) * 45,                       // J5 俯仰点头（±45°）
    Math.sin(w * 0.5) * 180,                // J6 腕部摆动（±180°，平滑无回绕）
  ];
}
